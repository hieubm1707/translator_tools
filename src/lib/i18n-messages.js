  const MESSAGES = { en, vi };
  const DEFAULT_LANG = 'en';
  const LOCALES = { en: 'en-US', vi: 'vi-VN' };
  const listeners = new Set();

  const i18n = {
    DEFAULT_LANG,
    LANGS: [['en', 'English'], ['vi', 'Tiếng Việt']],
    lang: DEFAULT_LANG,
    normalize: (lang) => (lang in MESSAGES ? lang : DEFAULT_LANG),
    // Ngôn ngữ khác thiếu key -> dùng tiếng Anh, thiếu luôn thì trả về chính key (dễ thấy khi quên khai báo).
    t(key, params, lang = i18n.lang) {
      const text = MESSAGES[lang]?.[key] ?? en[key] ?? key;
      return params ? text.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m)) : text;
    },
    locale: () => LOCALES[i18n.lang],
    setLang(lang) {
      const next = i18n.normalize(lang);
      if (next === i18n.lang) return;
      i18n.lang = next;
      for (const fn of listeners) fn(next);
    },
    onChange(fn) {
      listeners.add(fn);
    },
  };

  // Đọc ngôn ngữ đã lưu + theo dõi thay đổi (popup/trang/service worker/content script đều có chrome.storage).
  if (globalThis.chrome?.storage?.local) {
    chrome.storage.local.get({ uiLang: DEFAULT_LANG }).then(({ uiLang }) => i18n.setLang(uiLang)).catch(() => {});
    chrome.storage.onChanged.addListener((changes, area) => {
      if (area === 'local' && 'uiLang' in changes) i18n.setLang(changes.uiLang.newValue);
    });
  }

  globalThis.TT_I18N = i18n;
